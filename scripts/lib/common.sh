#!/usr/bin/env bash
# common.sh - shared helpers for hypr-arch-setup scripts.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
REPO_NAME="hypr-arch-setup"
GITHUB_USER="GFardad"
REMOTE="https://github.com/${GITHUB_USER}/${REPO_NAME}.git"
BRANCH="${BRANCH:-main}"
TIMESTAMP="$(date +%Y%m%d-%H%M%S)"

# The user we snapshot from live on the master machine. Rewritten on targets.
SOURCE_HOME="${SOURCE_HOME:-/home/gfardad}"

say()  { printf '\033[1;34m[%s]\033[0m %s\n' "$REPO_NAME" "$*"; }
ok()   { printf '\033[1;32m ✓\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m !\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m ✗\033[0m %s\n' "$*" >&2; exit 1; }

confirm() { # $1 prompt -> true/false
  local ans
  read -r -p "$1 [y/N] " ans
  [[ "${ans,,}" == y || "${ans,,}" == yes ]]
}

have() { command -v "$1" >/dev/null 2>&1; }

# ----------------------------------------------------------------
# Git helpers
# ----------------------------------------------------------------
repo_clean() { git -C "$REPO_ROOT" status --porcelain | grep -q . && return 1 || return 0; }

git_pull_rebase() {
  # Bring remote changes in without losing local state.
  git -C "$REPO_ROOT" pull --rebase --autostash origin "$BRANCH" \
    >/dev/null 2>&1 || git -C "$REPO_ROOT" pull --ff-only origin "$BRANCH" >/dev/null 2>&1 || true
}

git_push() {
  # Push; if remote moved, rebase on new remote head and retry once.
  if git -C "$REPO_ROOT" push origin "$BRANCH" >/dev/null 2>&1; then
    return 0
  fi
  git_pull_rebase
  git -C "$REPO_ROOT" push origin "$BRANCH" >/dev/null 2>&1
}

# ----------------------------------------------------------------
# Hardware neutralization (applied on TARGET machines, never master)
# ----------------------------------------------------------------
nvidia_present() { lspci 2>/dev/null | grep -qi 'vga.*nvidia\|3d.*nvidia'; }

rewrite_home_paths() {
  # $1 = file. Rewrites absolute master-home references to the target home.
  local f="$1" home
  home="${HOME:?}"
  [[ -f "$f" ]] || return 0
  sed -i "s#${SOURCE_HOME}#${home}#g" "$f" 2>/dev/null || true
}

strip_nvidia_env() {
  # $1 = hypr ENVariables file. Removes NVIDIA-only lines on non-NVIDIA boxes.
  local f="$1"
  [[ -f "$f" ]] || return 0
  sed -i -E \
    -e '/LIBVA_DRIVER_NAME=nvidia/d' \
    -e '/NVD_BACKEND=direct/d' \
    -e '/__GLX_VENDOR_LIBRARY_NAME=nvidia/d' \
    -e '/MOZ_DISABLE_RDD_SANDBOX=1/d' \
    -e '/__GL_SYNC_TO_VBLANK=0/d' \
    "$f" 2>/dev/null || true
}

drop_missing_exec() {
  # $1 = conf file with exec-once lines; drop entries whose command is missing.
  local f="$1" tmp
  [[ -f "$f" ]] || return 0
  tmp="$(mktemp)"
  while IFS= read -r line; do
    local cmd
    cmd="$(printf '%s' "$line" | sed -E 's/^[[:space:]]*exec-once[[:space:]]*=[[:space:]]*//; s/[&;|].*$//')"
    if have "${cmd%% *}"; then
      printf '%s\n' "$line"
    fi
  done < "$f" > "$tmp"
  cp "$tmp" "$f"; rm -f "$tmp"
}

neutralize_monitors() {
  # $1 = dest monitors.conf, $2 = dest workspaces.conf
  # Replace EDID-pinned monitor rules with something that works anywhere:
  # dims left to hyprland auto-detect; only keep vrr/bitdepth the user likes.
  local mon="$1" ws="$2"
  if grep -q '^desc:' "$mon" 2>/dev/null; then
    warn "monitors.conf is pinned to master hardware (EDID) - generating generic one"
    cat > "$mon" <<'EOF'
# monitors.conf - auto-generated by hypr-arch-setup installer.
# Remove per-monitor overrides; hyprland detects all outputs automatically.
EOF
    rm -f "$ws"
  fi
}